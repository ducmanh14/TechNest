CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, username VARCHAR(100) NOT NULL UNIQUE,
 fullname VARCHAR(150) NOT NULL,email VARCHAR(254) NULL UNIQUE,password_hash VARCHAR(255) NOT NULL,
 role ENUM('customer','admin') NOT NULL DEFAULT 'customer',
 auth_version INT UNSIGNED NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS categories (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,name VARCHAR(150) NOT NULL,
 slug VARCHAR(180) NOT NULL UNIQUE,
 is_active BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS brands LIKE categories;
CREATE TABLE IF NOT EXISTS products (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,category_id INT UNSIGNED NOT NULL,
 brand_id INT UNSIGNED NOT NULL,
 sku VARCHAR(64) NOT NULL UNIQUE,name VARCHAR(255) NOT NULL,description TEXT NOT NULL,
 specs_json JSON,
 price DECIMAL(15,0) NOT NULL,stock INT UNSIGNED NOT NULL DEFAULT 0,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 image_path VARCHAR(500) NOT NULL DEFAULT '/images/laptop.svg',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(category_id) REFERENCES categories(id),FOREIGN KEY(brand_id) REFERENCES brands(id),
 CHECK(price>=0),INDEX(category_id,brand_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS product_images (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,product_id INT UNSIGNED NOT NULL,
 image_path VARCHAR(500) NOT NULL,
 sort_order INT UNSIGNED NOT NULL DEFAULT 0,FOREIGN KEY(product_id) REFERENCES products(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS cart_items (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id INT UNSIGNED NOT NULL,
 product_id INT UNSIGNED NOT NULL,
 quantity INT UNSIGNED NOT NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE(user_id,product_id),FOREIGN KEY(user_id) REFERENCES users(id),
 FOREIGN KEY(product_id) REFERENCES products(id),CHECK(quantity>0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS orders (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,order_code VARCHAR(40) NOT NULL UNIQUE,
 user_id INT UNSIGNED NOT NULL,
 recipient_name VARCHAR(150) NOT NULL,phone VARCHAR(20) NOT NULL,shipping_address TEXT NOT NULL,
 subtotal DECIMAL(15,0) NOT NULL,shipping_fee DECIMAL(15,0) NOT NULL,total_amount DECIMAL(15,
 0) NOT NULL,
 status ENUM('pending','confirmed','shipping','delivered','cancelled') NOT NULL DEFAULT 'pending',
 payment_method VARCHAR(20) NOT NULL DEFAULT 'COD',payment_status ENUM('unpaid',
 'paid') NOT NULL DEFAULT 'unpaid',
 checkout_key CHAR(36) NOT NULL,request_hash CHAR(64) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 delivered_at TIMESTAMP NULL,
 UNIQUE(user_id,checkout_key),FOREIGN KEY(user_id) REFERENCES users(id),INDEX(user_id,created_at),
 INDEX(status,created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS order_items (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,order_id INT UNSIGNED NOT NULL,
 product_id INT UNSIGNED NOT NULL,
 product_name VARCHAR(255) NOT NULL,sku VARCHAR(64) NOT NULL,unit_price DECIMAL(15,0) NOT NULL,
 quantity INT UNSIGNED NOT NULL,line_total DECIMAL(15,0) NOT NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id),FOREIGN KEY(product_id) REFERENCES products(id),
 CHECK(quantity>0)
) ENGINE=InnoDB;